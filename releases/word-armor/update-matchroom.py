PUBLIC = "https://wordgame.educationstudio.cn/word-armor/"
PACKS = ("Word-Armor-Server.zip", "Word-Armor-LAN.zip")

def check(ok, message):
    if not ok:
        raise RuntimeError(message)

def call(base, route, data=None, key=""):
    payload = None if data is None else json.dumps(data).encode()
    req = Request(base+route, data=payload, headers={"Content-Type": "application/json", "X-Player": key})
    with urlopen(req, timeout=12) as response:
        return json.load(response)

def wait_ready():
    for attempt in range(20):
        try:
            if call(BASE, "healthz").get("ok"):
                return
        except OSError:
            pass
        time.sleep(0.5)
    raise RuntimeError("Local service health check failed")

def verify_game(base):
    for filename, digest in [["art.js","2f247edd6884804f9477f82e840883a1e2677e8ce17c7291ca6a5b034e0e0b35"],["app.js","132806dabcb417d176cad7f46de13242b079f053e45946f2c93a09a9a7e707c0"]]:
        with urlopen(base+filename+"?v=blast1", timeout=12) as response:
            check(hashlib.sha256(response.read()).hexdigest() == digest, "Game asset verification failed: "+filename)
    room = call(base, "api/rooms", {"size":1, "maxHP":7, "hint":"letters", "name":"Blue test", "wordSeconds":11, "shotSeconds":2.5})
    path = "api/rooms/"+room["code"]+"/"
    host = room["token"]
    guest = None
    try:
        guest = call(base, path+"join", {"team":1, "name":"Update test"}, "")["token"]
        check(room["practice"]["zh"]=="\u732b", "Host warm-up prompt missing")
        for key, word in [(host, "cat"), (guest, "book")]:
            practice = call(base, path+"practice", {"turn":0,"word":word}, key)
            check(practice["practiceCorrect"], "Server warm-up check failed")
        start = call(base, path+"start", {}, host)["game"]
        check(start.get("wordSeconds")==11 and start.get("shotSeconds")==2.5, "Custom timer settings missing")
        units = {t["id"]:t for t in start["tanks"]}
        check(units["A1"]["mask"] == "R_ _ _ _" and units["B1"]["hp"] == 7, "Clue or custom HP check failed")
        shot = call(base, path+"attack", {"word":"forest"}, host)
        other = call(base, path.rstrip("/"), None, guest)["game"]
        check(shot["correct"] and {t["id"]:t["hp"] for t in other["tanks"]} == {"A1":7,"B1":6}, "Word-only attack or synchronization failed")
    finally:
        for key in [guest, host]:
            if key:
                try: call(base, path+"leave", {}, key)
                except OSError: pass

def prepare_packages(source, dest):
    # Pinned application changes travel inside this updater. Large unchanged
    # resources and the Windows runtime come from the current installation.
    manifests, patches = json.loads(zlib.decompress(base64.b85decode(UPDATE_DATA)))
    for name, entries in manifests.items():
        with ZipFile(source/name) as old, ZipFile(dest/name, "w") as out:
            for filename, digest, date, method, system, mode, cv, ev, attr, extra, comment in entries:
                if digest in patches:
                    data = base64.b64decode(patches[digest])
                else:
                    data = old.read(filename)
                check(hashlib.sha256(data).hexdigest() == digest, "Source file checksum mismatch: " + filename)
                info = ZipInfo(filename, tuple(date))
                info.compress_type, info.create_system, info.external_attr = method, system, mode
                info.create_version, info.extract_version, info.internal_attr = cv, ev, attr
                info.extra, info.comment = bytes.fromhex(extra), bytes.fromhex(comment)
                out.writestr(info, data, compresslevel=6)
        # Compression output may differ between versions of zlib on Linux.
        # Verify every unpacked byte used for installation and for downloading.
        with ZipFile(dest/name) as out:
            check(len(out.infolist()) == len(entries), "Incomplete ZIP: " + name)
            for filename, digest, *_ in entries:
                check(hashlib.sha256(out.read(filename)).hexdigest()==digest, "Output checksum mismatch: " + filename)
        (dest/name).chmod(0o644)
        print("Verified", name, flush=True)

def update():
    check(os.geteuid() == 0, "Run as root or with sudo")
    check((LIVE/"server.mjs").is_file() and (LIVE/"public"/"index.html").is_file(), "Existing Word Armor installation not found")
    lock = open("/run/lock/word-armor-update.lock", "a")
    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    subprocess.run(["systemctl","is-active","--quiet",SERVICE], check=True)
    check(call(BASE, "healthz").get("edition") == "server", "Expected server edition under /word-armor/")
    work = Path(tempfile.mkdtemp(prefix="word-armor-update.", dir=LIVE.parent))
    stage = work/"stage"
    backup = work/"previous"
    stage.mkdir()
    backup.mkdir()
    (stage/"downloads").mkdir()
    print("Preparing checked packages in", work, flush=True)
    prepare_packages(LIVE/"downloads", stage/"downloads")
    files = []
    with ZipFile(stage/"downloads"/"Word-Armor-Server.zip") as archive:
        for item in archive.infolist():
            if item.is_dir() or not item.filename.startswith("Word-Armor-Server/"):
                continue
            rel = Path(item.filename[len("Word-Armor-Server/"):])
            if rel.is_absolute() or ".." in rel.parts:
                raise RuntimeError("Invalid archive path")
            if rel.as_posix() not in ("game.mjs", "server.mjs") and rel.parts[:1] != ("public",):
                continue
            dest = stage/rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(archive.read(item))
            files.append(rel)
    check(all(Path(p) in files for p in ["game.mjs","server.mjs","public/index.html","public/engine.js","public/app.js"]), "Incomplete server package")
    files += [Path("downloads")/name for name in PACKS]
    for rel in files:
        target = LIVE/rel
        check((target.parent.resolve() == LIVE.resolve() or LIVE.resolve() in target.parent.resolve().parents) and not target.is_symlink(), "Unexpected installation layout: "+str(rel))
        target.parent.mkdir(parents=True, exist_ok=True)
        check(not target.exists() or target.is_file(), "Unexpected file type: "+str(rel))
        if target.is_file():
            old = backup/rel
            old.parent.mkdir(parents=True, exist_ok=True)
            os.link(target, old)
            original = target.stat()
            os.chown(stage/rel, original.st_uid, original.st_gid)
            (stage/rel).chmod(stat.S_IMODE(original.st_mode))
    changed = []
    try:
        for rel in files:
            os.replace(stage/rel, LIVE/rel)
            changed.append(rel)
        subprocess.run(["systemctl","restart",SERVICE], check=True)
        wait_ready()
        verify_game(BASE)
    except BaseException:
        if changed:
            for rel in reversed(changed):
                old = backup/rel
                if old.exists(): os.replace(old, LIVE/rel)
                else: (LIVE/rel).unlink()
            subprocess.run(["systemctl","restart",SERVICE], check=True)
            wait_ready()
            print("Restored previous game files and service.", flush=True)
        raise
    print("Local release and two-player match verified. Previous files:",backup,flush=True)
    verify_game(PUBLIC)
    for name in PACKS:
        req = Request(PUBLIC+"downloads/"+name, method="HEAD")
        with urlopen(req,timeout=15) as response:
            check(int(response.headers["Content-Length"]) == (LIVE/"downloads"/name).stat().st_size, "Download size mismatch: "+name)
    print("WORD ARMOR UPDATE OK - public multiplayer and both downloads verified", flush=True)

